/// Categories for Tafsir and Translation books.
/// Aligns with the categories presented in Library Sheet (Reference 34).
/// Pure Dart — no Flutter framework dependencies.
enum TafsirCategory {
  /// Arabic Tafsir books (e.g. Al-Muyassar, Al-Saadi, Ibn Kathir).
  arabicTafsir,

  /// Arabic Grammar and Quranic Linguistics (e.g. I'rab al-Quran).
  arabicGrammar,

  /// English Translations and Commentary (e.g. Sahih International, Tafheem).
  englishTranslation,

  /// Translations in various global languages.
  otherTranslations,
}

